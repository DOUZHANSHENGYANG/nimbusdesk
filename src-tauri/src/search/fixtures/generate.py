"""Regenerate synthetic extraction fixtures; no downloaded/user documents.

Uses Python stdlib and the already available ReportLab for a CID Chinese PDF.
The PDF contains a real text layer, not a bitmap/OCR result.
"""
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED
from reportlab.pdfgen import canvas
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.cidfonts import UnicodeCIDFont
from docx import Document
from openpyxl import Workbook
from pptx import Presentation

root = Path(__file__).parent

def package(name, entries):
    with ZipFile(root / name, "w", ZIP_DEFLATED) as archive:
        for member, body in entries.items():
            archive.writestr(member, body)

package("document.docx", {
    "word/document.xml": '<w:document xmlns:w="urn:word"><w:body><w:p><w:r><w:t>开发知识 &amp; 搜索</w:t></w:r></w:p><w:tbl><w:tr><w:tc><w:p><w:r><w:t>表格内容</w:t></w:r></w:p></w:tc></w:tr></w:tbl></w:body></w:document>',
    "word/footnotes.xml": '<w:footnotes xmlns:w="urn:word"><w:p><w:r><w:t>脚注文本</w:t></w:r></w:p></w:footnotes>',
    "docProps/core.xml": '<core>secret metadata</core>',
})
package("workbook.xlsx", {
    "xl/sharedStrings.xml": '<sst><si><t>共享字符串</t></si><si><r><t>未引用</t></r><r><t>文本</t></r></si></sst>',
    "xl/worksheets/sheet1.xml": '<worksheet><sheetData><row><c t="s"><v>0</v></c><c t="inlineStr"><is><t>内联内容</t></is></c><c><v>42</v></c></row></sheetData></worksheet>',
})
package("presentation.pptx", {
    "ppt/slides/slide10.xml": '<p:sld xmlns:p="urn:p" xmlns:a="urn:a"><a:p><a:r><a:t>第十页</a:t></a:r></a:p></p:sld>',
    "ppt/slides/slide2.xml": '<p:sld xmlns:p="urn:p" xmlns:a="urn:a"><a:p><a:r><a:t>第二页</a:t></a:r></a:p></p:sld>',
})
package("oversized.docx", {"word/document.xml": " " * (8 * 1024 * 1024 + 1)})
package("too-many.docx", {f"empty/{i}": "" for i in range(4097)})
package("cumulative.docx", {f"word/header{i}.xml": " " * (8 * 1024 * 1024) for i in range(9)})
package("large-image.docx", {
    "word/document.xml": '<w:document xmlns:w="urn:word"><w:p><w:r><w:t>带大图的文档</w:t></w:r></w:p></w:document>',
    "word/media/image.png": " " * (16 * 1024 * 1024),
})
for name in ["corrupt.docx", "corrupt.pdf", "legacy.doc"]:
    (root / name).write_bytes(b"invalid document fixture")
(root / "sample.xml").write_text('<note><title>你好 &amp; 世界</title><body><![CDATA[正文 <原样>]]></body></note>', encoding="utf-8")
(root / "external-entity.xml").write_text('<!DOCTYPE note [<!ENTITY remote SYSTEM "file:///does-not-exist">]><note>&remote;</note>', encoding="utf-8")
(root / "ifilter-probe.txt").write_text("开发知识 Windows IFilter", encoding="utf-8-sig")
pdfmetrics.registerFont(UnicodeCIDFont("STSong-Light"))
pdf = canvas.Canvas(str(root / "chinese-text.pdf"), invariant=True)
pdf.setFont("STSong-Light", 14)
pdf.drawString(50, 780, "开发知识：中文正文检索 Office PDF")
pdf.save()
pdf = canvas.Canvas(str(root / "scanned.pdf"), invariant=True)
pdf.rect(50, 700, 250, 60, fill=True)
pdf.save()
pdf = canvas.Canvas(str(root / "encrypted.pdf"), invariant=True, encrypt="fixture-password")
pdf.drawString(50, 780, "Protected fixture")
pdf.save()

# Complete, interoperable Office packages generated by normal producer libraries.
document = Document()
document.add_heading("开发知识真实 Office 样本", 0)
document.add_paragraph("DOCX 中文正文与全局搜索")
document.add_table(rows=1, cols=1).cell(0, 0).text = "表格中的唯一词：知识配方"
document.save(root / "real-document.docx")
workbook = Workbook()
workbook.active["A1"] = "XLSX 中文单元格：计划附件"
workbook.active["B1"] = 2026
workbook.save(root / "real-workbook.xlsx")
presentation = Presentation()
slide = presentation.slides.add_slide(presentation.slide_layouts[1])
slide.shapes.title.text = "PPTX 中文演示：桌面工作台"
slide.placeholders[1].text = "正文索引与拼音搜索"
presentation.save(root / "real-presentation.pptx")
