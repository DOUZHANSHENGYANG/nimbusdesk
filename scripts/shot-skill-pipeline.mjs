import { loadPlaywright, resolveBrowser } from "./browser-harness.mjs";
const { chromium } = await loadPlaywright();
const b = await chromium.launch({ executablePath: resolveBrowser(), headless: true });
const p = await b.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
const errs=[]; p.on("pageerror",e=>errs.push(e.message));
await p.goto("http://127.0.0.1:17800/src/ahub/fixtures/tag-shelf.html");
await p.waitForTimeout(2200);
await p.getByRole("button",{name:/批量选择/}).click();
await p.waitForTimeout(400);
const boxes = await p.locator('[role="checkbox"], input[type="checkbox"]').count();
console.log("checkboxes", boxes);
await p.getByText("代码评审",{exact:false}).first().click();
await p.waitForTimeout(400);
await p.getByRole("button",{name:/流水线/}).click();
await p.waitForTimeout(800);
await p.getByRole("button",{name:/开始/}).click();
await p.waitForTimeout(1500);
await p.screenshot({ path: "E:/01-Desktop/仙台/工作台软件/docs/screenshots/skill-pipeline.png" });
console.log("errors", errs.slice(0,3));
await b.close();
