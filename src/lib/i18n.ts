export const i18n = i18next.createInstance();
void i18n.init({
  lng: "zh",
  fallbackLng: "en",
  defaultNS: "translation",
  resources: {
    zh: { translation: zh },
    en: { translation: en },
  },
  interpolation: { escapeValue: false },
});

export function changeLang(lang: Lang) {
  if (i18n.language !== lang) void i18n.changeLanguage(lang);
}

