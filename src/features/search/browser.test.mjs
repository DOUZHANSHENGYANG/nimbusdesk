// Run against Temp/search-review.html served by Vite. Reuses the installed browser runtime.
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';

const runtime = process.env.SEARCH_PLAYWRIGHT_PATH;
if (!runtime) throw new Error('Set SEARCH_PLAYWRIGHT_PATH to an existing playwright/index.mjs.');
const { chromium } = await import(pathToFileURL(runtime).href);
const browser = await chromium.launch({ headless: true, ...(process.env.SEARCH_BROWSER_PATH ? { executablePath: process.env.SEARCH_BROWSER_PATH } : {}) });
try {
  const page = await browser.newPage({ viewport: { width: 760, height: 560 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const url = `${process.env.SEARCH_REVIEW_ORIGIN || 'http://127.0.0.1:17802'}/Temp/search-review.html`;
  await page.goto(url);
  const input = page.getByRole('combobox');
  await input.waitFor();
  const hides = () => page.evaluate(() => window.searchReview.calls.filter(call => call.cmd === 'plugin:window|hide').length);
  const beforeBlur = await hides();
  await page.evaluate(() => {
    window.searchReview.hasFocus = true;
    Object.defineProperty(document, 'hasFocus', { configurable: true, value: () => window.searchReview.hasFocus });
    window.dispatchEvent(new FocusEvent('blur'));
  });
  await page.waitForTimeout(240);
  assert.equal(await hides(), beforeBlur, 'a native blur notification cannot hide a still-focused document');
  await page.evaluate(() => {
    window.searchReview.hasFocus = false;
    window.dispatchEvent(new FocusEvent('blur'));
    setTimeout(() => { window.searchReview.hasFocus = true; window.dispatchEvent(new FocusEvent('focus')); }, 50);
  });
  await page.waitForTimeout(240);
  assert.equal(await hides(), beforeBlur, 'transient focus loss recovers before the delayed check');
  await page.evaluate(() => { window.searchReview.hasFocus = false; window.dispatchEvent(new FocusEvent('blur')); });
  await page.waitForTimeout(80);
  assert.equal(await hides(), beforeBlur, 'stable focus loss must respect the hide delay');
  await page.waitForTimeout(180);
  assert.equal(await hides(), beforeBlur + 1, 'stable focus loss hides the native window once');
  await input.dispatchEvent('compositionstart');
  await page.evaluate(() => window.dispatchEvent(new FocusEvent('blur')));
  await page.waitForTimeout(240);
  assert.equal(await hides(), beforeBlur + 1, 'IME composition suppresses blur hiding even when document focus is false');
  await input.dispatchEvent('compositionend');
  await page.evaluate(() => { delete document.hasFocus; window.dispatchEvent(new FocusEvent('focus')); });
  await input.fill('existing'); await page.waitForTimeout(250);
  const beforeNewQuery = await page.evaluate(() => window.searchReview.calls.filter(call => call.cmd === 'search_open_result').length);
  await input.fill('slow'); await input.press('Enter');
  assert.equal(await page.evaluate(() => window.searchReview.calls.filter(call => call.cmd === 'search_open_result').length), beforeNewQuery, 'Enter before the new query publishes cannot open a previous query result');
  const beforeStalePreview = await page.evaluate(() => window.searchReview.calls.filter(call => call.cmd === 'search_preview').length);
  await page.getByRole('button', {name:'预览',exact:true}).first().click();
  await page.locator('.quick-search-result-main').first().click();
  assert.equal(await page.evaluate(() => window.searchReview.calls.filter(call => call.cmd === 'search_open_result').length), beforeNewQuery, 'clicking a stale row cannot open it');
  assert.equal(await page.evaluate(() => window.searchReview.calls.filter(call => call.cmd === 'search_preview').length), beforeStalePreview, 'a stale row cannot be previewed');
  await page.waitForTimeout(800); await input.press('Enter');
  assert.equal(await page.evaluate(() => window.searchReview.calls.filter(call => call.cmd === 'search_open_result').length), beforeNewQuery + 1);
  assert.match(await page.evaluate(() => window.searchReview.calls.filter(call => call.cmd === 'search_open_result').at(-1).args.result.title), /slow/);
  await page.getByRole('button', {name:'全部',exact:true}).click(); await input.press('Enter');
  assert.equal(await page.evaluate(() => window.searchReview.calls.filter(call => call.cmd === 'search_open_result').length), beforeNewQuery + 2, 'clicking the already active scope preserves valid result actions');
  await page.evaluate(() => window.searchReview.slowFiles = true);
  await input.fill('快业务'); await page.waitForTimeout(250);
  assert.equal(await page.locator('[role=option]').count(), 2);
  await input.press('ArrowDown');
  assert.match(await page.locator('[role=option][aria-selected=true]').innerText(), /设计评审/);
  await page.waitForTimeout(650);
  assert.equal(await page.locator('[role=option]').count(), 3);
  assert.match(await page.locator('[role=option][aria-selected=true]').innerText(), /设计评审/);
  await input.fill('旧文件'); await page.waitForTimeout(200);
  await input.fill('新文件'); await page.waitForTimeout(850);
  assert.ok((await page.locator('[role=option]').allInnerTexts()).every(text => text.includes('新文件')));
  await page.evaluate(() => { window.searchReview.slowFiles = false; window.searchReview.rejectFiles = true; });
  await input.fill('文件降级'); await page.waitForTimeout(200);
  assert.equal(await page.locator('[role=option]').count(), 2);
  assert.match(await page.locator('.quick-search-notice').innerText(), /工作台结果/);
  await page.evaluate(() => window.searchReview.rejectFiles = false);
  await input.fill('slow'); await page.waitForTimeout(180);
  await input.fill('新版'); await page.waitForTimeout(850);
  assert.match(await page.locator('[role=option]').first().innerText(), /新版/);
  assert.equal(await page.locator('[role=option]').count(), 3);
  await input.dispatchEvent('compositionstart'); await input.fill('组词'); await page.waitForTimeout(200);
  assert.equal(await page.evaluate(() => window.searchReview.calls.filter(x => x.cmd === 'search_query' && x.args.query === '组词').length), 0);
  await input.dispatchEvent('compositionend'); await page.waitForTimeout(200);
  assert.ok(await page.evaluate(() => window.searchReview.calls.some(x => x.cmd === 'search_query' && x.args.query === '组词')));
  await input.press('ArrowDown'); await page.keyboard.press('Control+Enter');
  assert.equal(await page.evaluate(() => window.searchReview.calls.filter(x => x.cmd === 'search_open_result').at(-1).args.action), 'reveal');
  assert.equal(await page.evaluate(() => window.searchReview.calls.filter(x => x.cmd === 'search_open_result').at(-1).args.result.id), 'file-组词');
  await page.keyboard.press('Space'); await page.getByRole('complementary').waitFor();
  assert.match(await page.getByRole('complementary').innerText(), /统一搜索/);
  await page.keyboard.press('Escape'); assert.equal(await page.getByRole('complementary').count(), 0);
  await page.keyboard.press('Tab'); await page.waitForTimeout(180);
  assert.equal(await page.evaluate(() => window.searchReview.calls.filter(x => x.cmd === 'search_query').at(-1).args.scope), 'file');
  await input.fill('broken'); await page.waitForTimeout(200);
  assert.equal(await page.locator('[role=option]').count(), 1);
  assert.match(await page.locator('.quick-search-notice').innerText(), /保留/);
  await input.fill('项目'); await page.waitForTimeout(200);
  const beforeRefresh = await page.evaluate(() => window.searchReview.calls.filter(x => x.cmd === 'search_query').length);
  await page.evaluate(() => window.searchReview.store.setState({ status: { ...window.searchReview.store.getState().status, lastIndexedAt: 2 } }));
  await page.waitForTimeout(180);
  assert.ok(await page.evaluate(() => window.searchReview.calls.filter(x => x.cmd === 'search_query').length) > beforeRefresh);
  await page.evaluate(() => { navigator.clipboard.writeText = async value => { window.searchReview.copied = value; }; });
  await input.press('ArrowDown'); await page.keyboard.press('Control+c');
  assert.match(await page.evaluate(() => window.searchReview.copied), /项目-notes\.md$/);
  await input.focus(); await input.evaluate(element => element.setSelectionRange(0, 1));
  await page.evaluate(() => window.searchReview.copied = 'untouched');
  await input.press('Control+c');
  assert.equal(await page.evaluate(() => window.searchReview.copied), 'untouched');
  await input.press('Space'); assert.equal(await page.getByRole('complementary').count(), 0);
  if (process.env.SEARCH_REVIEW_SCREENSHOT) await page.screenshot({ path: process.env.SEARCH_REVIEW_SCREENSHOT });
  await page.setViewportSize({ width: 560, height: 420 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.goto(`${url}?settings`);
  const shortcut = page.getByLabel('全局快捷键', { exact: true });
  await shortcut.waitFor(); await page.waitForTimeout(160);
  assert.equal(await shortcut.inputValue(), 'Alt+K');
  assert.equal(await page.evaluate(() => window.searchReview.calls.filter(x => x.cmd === 'write_json').length), 0);
  await shortcut.fill('Ctrl+Alt+J'); await page.evaluate(() => window.searchReview.rejectShortcut = true);
  await page.getByRole('button', { name: '保存', exact: true }).click(); await page.getByRole('alert').waitFor();
  assert.equal(await page.evaluate(() => window.searchReview.fixtures['search-settings'].state.shortcut), 'Alt+K');
  assert.equal(await page.evaluate(() => window.searchReview.calls.filter(x => x.cmd === 'write_json').length), 0);
  await page.evaluate(() => { window.searchReview.rejectShortcut = false; window.searchReview.rejectWrite = true; });
  await page.getByRole('button', { name: '保存', exact: true }).click(); await page.waitForTimeout(180);
  assert.equal(await page.evaluate(() => window.searchReview.calls.filter(x => x.cmd === 'search_set_shortcut').at(-1).args.shortcut), 'Alt+K');
  await page.evaluate(() => window.searchReview.rejectWrite = false);
  await page.getByRole('button', { name: '保存', exact: true }).click(); await page.waitForTimeout(180);
  assert.equal(await page.evaluate(() => window.searchReview.fixtures['search-settings'].state.shortcut), 'Ctrl+Alt+J');
  assert.deepEqual(errors, []);
  console.log('PASS: new query immediately blocks stale Enter, row open and preview; current reply restores actions; active scope click preserves actions; focused/transient blur no-hide, delayed stable blur hide, IME blur no-hide; slow files preserve fast business and selected ID, stale replies, IME query suppression, selection/reveal, preview/Escape, Tab scopes, copy path vs input selection, input Space typing, index completion requery, failure preserves results, 560px layout, hydration no write, shortcut conflict, write rollback, explicit save; no page errors.');
} finally { await browser.close(); }
