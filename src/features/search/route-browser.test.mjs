import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const { chromium } = await import(pathToFileURL(process.env.SEARCH_PLAYWRIGHT_PATH).href);
const browser = await chromium.launch({headless:true,executablePath:process.env.SEARCH_BROWSER_PATH});
try {
 const page=await browser.newPage({viewport:{width:1300,height:880}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 const base=`${process.env.SEARCH_REVIEW_ORIGIN||'http://127.0.0.1:17802'}/src/features/search/fixtures/page.html?integration`;
 await page.goto(base+'#/plans?date=2099-10-18&task=child');
 await page.locator('[data-search-task-id="child"]').waitFor();
 console.log('Route: dated task visible');
 assert.match(await page.locator('[data-search-task-id="child"]').getAttribute('class'),/ring-brand/);
 const parent=page.locator('[data-search-task-id="parent"]');
 await parent.getByRole('button').first().click();
 assert.equal(await page.locator('[data-search-task-id="child"]').count(),0);
 await page.evaluate(()=>location.hash='/plans?date=2099-10-18&task=child&again=1');
 await page.locator('[data-search-task-id="child"]').waitFor();
 console.log('Route: collapsed ancestors reopened');
 await page.evaluate(()=>location.hash='/plans?date=2020-10-18&task=archived&archived=1');
 await page.locator('[data-search-task-id="archived"]').waitFor();
 assert.match(await page.locator('[data-search-task-id="archived"]').getAttribute('class'),/ring-brand/);
 console.log('Route: archived task visible');
 await page.evaluate(()=>location.hash='/knowledge?note=inbox%2Ftarget.md');
 await page.locator('.knowledge-note-open[aria-current="true"]').filter({hasText:'搜索目标笔记'}).waitFor();
 assert.match(await page.locator('.knowledge-note-open[aria-current="true"]').innerText(),/搜索目标笔记/);
 console.log('Route: requested knowledge selected');
 await page.getByRole('button',{name:'编辑',exact:true}).click();
 await page.getByRole('textbox',{name:'Markdown 编辑器'}).fill('未保存的本地草稿');
 await page.evaluate(()=>location.hash='/knowledge?note=inbox%2Ffirst.md');
 await page.waitForTimeout(200);
 assert.match(await page.locator('.knowledge-note-open[aria-current="true"]').innerText(),/搜索目标笔记/);
 assert.equal(await page.getByRole('textbox',{name:'Markdown 编辑器'}).inputValue(),'未保存的本地草稿');
 await page.getByRole('button',{name:'保存笔记',exact:true}).click();
 await page.locator('.knowledge-note-open[aria-current="true"]').filter({hasText:'首篇默认笔记'}).waitFor();
 console.log('Route: dirty note retained and pending navigation resumed after save');
 await page.evaluate(()=>location.hash='/feeds?source=github-trending&article=https%3A%2F%2Fexample.test%2Fcached');
 await page.getByText('缓存搜索目标资讯',{exact:true}).first().waitFor();
 assert.equal(await page.locator('button[title="缓存搜索目标资讯"]').getAttribute('aria-pressed'),'true');
 await page.evaluate(()=>location.hash='/feeds?source=__favorites__&article=https%3A%2F%2Fexample.test%2Ffavorite');
 await page.getByRole('heading',{name:'收藏搜索目标资讯',exact:true}).waitFor();
 await page.evaluate(()=>location.hash='/files?item=bookmark');
 await page.locator('[data-item-id="bookmark"]').waitFor();
 assert.match(await page.locator('[data-item-id="bookmark"]').getAttribute('class'),/border-brand/);
 await page.evaluate(()=>location.hash='/settings?tab=search');
 await page.getByRole('heading',{name:'快捷搜索',exact:true}).waitFor();
 await page.getByRole('button',{name:'全局搜索',exact:true}).click();
 assert.ok(await page.evaluate(()=>window.searchReview.calls.some(call=>call.cmd==='search_open_window')));
 await page.evaluate(()=>window.searchReview.emitNavigate('search://navigate','/plans?date=2099-10-18&task=child'));
 await page.locator('[data-search-task-id="child"]').waitFor();
 assert.deepEqual(errors,[]);
 console.log('PASS: main window search entry/settings, native navigation bridge, dated nested task expansion and highlight, archived task reveal, requested knowledge independent of first selection, dirty editor guard and post-save navigation, cached/favorite article selection, bookmarked file highlight; no page errors.');
} finally {await browser.close();}
