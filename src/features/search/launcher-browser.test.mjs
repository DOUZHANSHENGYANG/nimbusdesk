import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const { chromium } = await import(pathToFileURL(process.env.SEARCH_PLAYWRIGHT_PATH).href);
const browser = await chromium.launch({headless:true,executablePath:process.env.SEARCH_BROWSER_PATH});
try {
 const page=await browser.newPage({viewport:{width:760,height:650}}), errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 const base=`${process.env.SEARCH_REVIEW_ORIGIN||'http://127.0.0.1:17802'}/src/features/search/fixtures/launcher.html`;
 await page.goto(base);
 await page.getByRole('button',{name:'应用',exact:true}).waitFor({timeout:15000});
 await page.getByText('固定应用',{exact:true}).waitFor();
 await page.getByText('最近打开',{exact:true}).waitFor();
 assert.equal(await page.locator('[role=option]').count(),2,'home deduplicates pinned recent entry');
 await page.evaluate(async()=>{window.searchReview.home.recent.push({id:'app:event',kind:'app',title:'事件应用',subtitle:'',snippet:'',score:1});await window.searchReview.emitNavigate('search://home',{});});
 await page.getByText('事件应用',{exact:true}).waitFor();
 await page.getByRole('combobox').dispatchEvent('compositionstart');
 await page.evaluate(async()=>{await window.searchReview.emitNavigate('search://home',{});});
 await page.waitForTimeout(80);
 await page.getByRole('button',{name:'取消固定',exact:true}).click();
 assert.equal(await page.evaluate(()=>window.searchReview.calls.filter(call=>call.cmd==='search_pin').length),0,'a home refresh cannot reactivate actions during IME composition');
 await page.getByRole('combobox').dispatchEvent('compositionend');
 await page.getByRole('button',{name:'取消固定',exact:true}).click();
 assert.equal(await page.getByText('固定',{exact:true}).count(),0);
 await page.getByRole('button',{name:'清空最近',exact:true}).click();
 assert.equal(await page.locator('[role=option]').count(),0);
 await page.getByRole('combobox').fill('wx');
 await page.getByText('微信',{exact:true}).waitFor();
 await page.getByRole('button',{name:'固定',exact:true}).click();
 await page.getByRole('button',{name:'取消固定',exact:true}).waitFor();
 await page.getByRole('combobox').fill('');
 await page.getByText('微信',{exact:true}).waitFor();
 await page.getByRole('combobox').press('ArrowDown');await page.getByRole('listbox').press('Enter');
 assert.equal(await page.evaluate(()=>window.searchReview.calls.filter(call=>call.cmd==='search_open_result').at(-1).args.result.id),'app:wechat');
 await page.goto(base+'?settings');
 await page.getByLabel('文件名索引上限',{exact:true}).waitFor();
 assert.equal(await page.getByLabel('文件名索引上限',{exact:true}).inputValue(),'250000');
 await page.getByRole('button',{name:'不索引文件名',exact:true}).click();
 await page.getByLabel('文件名索引上限',{exact:true}).fill('40000');
 await page.getByRole('switch',{name:'隐藏常见噪音目录',exact:true}).click();
 await page.getByRole('button',{name:'保存',exact:true}).first().click();
 await page.getByText('搜索设置已保存',{exact:true}).waitFor();
 const state=await page.evaluate(()=>window.searchReview.fixtures['search-settings'].state);
 assert.deepEqual(state.nameRoots,[]);assert.equal(state.nameIndexLimit,40000);assert.equal(state.hideNoisyResults,false);
 assert.equal(state.documentRoots,null,'filename range does not replace content range');
 await page.evaluate(()=>window.searchReview.pick=['E:/名称目录','E:/另一个名称目录']);
 await page.getByRole('button',{name:'添加文件名目录',exact:true}).click();
 await page.getByRole('button',{name:'保存',exact:true}).first().click();
 await page.getByText('搜索设置已保存',{exact:true}).waitFor();
 assert.deepEqual(await page.evaluate(()=>window.searchReview.fixtures['search-settings'].state.nameRoots),['E:/名称目录','E:/另一个名称目录']);
 await page.getByRole('button',{name:'全部位置',exact:true}).click();
 await page.getByRole('button',{name:'保存',exact:true}).first().click();
 await page.getByText('搜索设置已保存',{exact:true}).waitFor();
 assert.equal(await page.evaluate(()=>window.searchReview.fixtures['search-settings'].state.nameRoots),null);
 const quick=page.getByRole('region',{name:'选中文字快捷工具',exact:true});
 assert.equal(await page.evaluate(()=>window.searchReview.calls.some(call=>call.cmd==='quick_tools_set_shortcut')),false,'hydration never registers a shortcut');
 await quick.getByLabel('全局快捷键',{exact:true}).fill('Ctrl+Alt+Y');
 await page.evaluate(()=>window.searchReview.rejectShortcut=true);
 await quick.getByRole('button',{name:'保存',exact:true}).click();
 await quick.getByRole('alert').filter({hasText:'SHORTCUT_CONFLICT'}).waitFor();
 assert.equal(await page.evaluate(()=>window.searchReview.fixtures['quick-tools-settings']),undefined);
 await page.evaluate(()=>window.searchReview.rejectShortcut=false);
 await page.evaluate(()=>window.searchReview.rejectWrite=true);
 await quick.getByRole('button',{name:'保存',exact:true}).click();
 await quick.getByRole('alert').filter({hasText:'WRITE_FAILED'}).waitFor();
 const shortcuts=await page.evaluate(()=>window.searchReview.calls.filter(call=>call.cmd==='quick_tools_set_shortcut').map(call=>call.args.shortcut));
 assert.deepEqual(shortcuts.slice(-2),['Ctrl+Alt+Y','Ctrl+Alt+T'],'failed persistence restores native shortcut');
 assert.equal(await quick.getByLabel('全局快捷键',{exact:true}).inputValue(),'Ctrl+Alt+Y','failed save retains draft');
 await page.evaluate(()=>window.searchReview.rejectWrite=false);
 await quick.getByLabel('全局快捷键',{exact:true}).fill('');
 await quick.getByRole('button',{name:'保存',exact:true}).click();
 await quick.getByText('快捷工具设置已保存',{exact:true}).waitFor();
 assert.equal(await page.evaluate(()=>window.searchReview.fixtures['quick-tools-settings'].state.shortcut),'');
 assert.equal(await page.evaluate(()=>window.searchReview.calls.some(call=>call.cmd==='ai_chat')),false);
 await page.goto(base+'?settings&quickreadfail');
 const failedQuick=page.getByRole('region',{name:'选中文字快捷工具',exact:true});
 await failedQuick.getByRole('alert').filter({hasText:'READ_FAILED'}).waitFor();
 assert.equal(await failedQuick.getByRole('button',{name:'保存',exact:true}).isDisabled(),true);
 assert.equal(await page.evaluate(()=>window.searchReview.calls.some(call=>call.cmd==='write_json'||call.cmd==='quick_tools_set_shortcut')),false);
 await page.evaluate(()=>window.searchReview.rejectQuickRead=false);
 await failedQuick.getByRole('button',{name:'重新读取设置',exact:true}).click();
 await failedQuick.getByLabel('全局快捷键',{exact:true}).fill('Ctrl+Alt+U');
 assert.equal(await failedQuick.getByRole('button',{name:'保存',exact:true}).isDisabled(),false);
 await page.goto(base+'?settings&quickshortcuterror');
 const startupQuick=page.getByRole('region',{name:'选中文字快捷工具',exact:true});
 await startupQuick.getByRole('alert').filter({hasText:'STARTUP_SHORTCUT_CONFLICT'}).waitFor();
 await startupQuick.getByRole('button',{name:'保存',exact:true}).click();
 await startupQuick.getByText('快捷工具设置已保存',{exact:true}).waitFor();
 assert.equal(await startupQuick.getByRole('alert').count(),0,'successful retry clears startup shortcut error');
 await page.evaluate(async()=>{window.searchReview.shortcutError='NEW_SHORTCUT_CONFLICT';await window.searchReview.emitNavigate('quick-tools://shortcut-error','NEW_SHORTCUT_CONFLICT');});
 await startupQuick.getByRole('alert').filter({hasText:'NEW_SHORTCUT_CONFLICT'}).waitFor();
 assert.deepEqual(errors,[]);
 console.log('PASS launcher home, pins/recent, app keyboard activation, separate filename range/cap/noise, quick-tools shortcut rollback/disable and explicit AI privacy.');
} finally {await browser.close();}
